import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import AiFindPrototype from './AiFindPrototype.vue'
import { useDemoConversation } from './demoConversation'

beforeEach(() => { vi.useFakeTimers(); useDemoConversation('pc').newSession() })
afterEach(() => { vi.useRealTimers() })
async function finish() { await vi.runAllTimersAsync(); await flushPromises() }

describe('纯前端交互原型', () => {
  it('does not pull a reader to the bottom when a confirmed-plan search finishes', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找煤炭运价，必须按天查看、每天更新')
    await wrapper.get('form.composer-box').trigger('submit'); await finish()
    await wrapper.get('.plan-option').trigger('click')
    await wrapper.get('.confirm-panel button').trigger('click')
    const area = wrapper.get('[data-testid="prototype-conversation"]')
    Object.defineProperty(area.element, 'scrollHeight', { configurable: true, value: 2000 })
    Object.defineProperty(area.element, 'clientHeight', { configurable: true, value: 200 })
    area.element.scrollTop = 100; await area.trigger('scroll')
    await finish()
    expect(area.element.scrollTop).toBe(100)
    expect(wrapper.get('.latest-bar').text()).toContain('有新内容')
    wrapper.unmount()
  })
  it('offers stop during processing and protects the next draft until stopped', async () => {
    const wrapper = mount(AiFindPrototype)
    const input = wrapper.get('textarea[aria-label="描述数据需求"]')
    await input.setValue('找2025年煤炭运价')
    await wrapper.get('form.composer-box').trigger('submit')
    await input.setValue('改成2024年')
    await wrapper.get('form.composer-box').trigger('submit')
    expect(wrapper.findAll('.conversation-turn')).toHaveLength(1)
    await wrapper.get('[aria-label="停止本批处理"]').trigger('click')
    await finish()
    expect(wrapper.get('.conversation-turn').attributes('data-phase')).toBe('stopped')
    expect((input.element as HTMLTextAreaElement).value).toBe('改成2024年')
    wrapper.unmount()
  })

  it('records a downvote immediately without requiring a reason', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找2025年煤炭运价')
    await wrapper.get('form.composer-box').trigger('submit'); await finish()
    await wrapper.get('[aria-label="点踩此回答"]').trigger('click')
    await wrapper.get('[aria-label="关闭弹窗"]').trigger('click')
    expect(wrapper.get('[aria-label="点踩此回答"]').attributes('aria-pressed')).toBe('true')
    await wrapper.get('[aria-label="点赞此回答"]').trigger('click')
    expect(wrapper.get('[aria-label="点踩此回答"]').attributes('aria-pressed')).toBe('false')
    expect(wrapper.find('[aria-label="复制答案"]').exists()).toBe(false)
    wrapper.unmount()
  })

  it('asks for confirmation before deleting an entire session', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找2025年煤炭运价')
    await wrapper.get('form.composer-box').trigger('submit')
    const id = useDemoConversation('pc').session.id
    await wrapper.get('[aria-label="历史会话"]').trigger('click')
    await wrapper.get(`[data-delete-session="${id}"]`).trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('停止本会话')
    expect(useDemoConversation('pc').state.sessions.some(s => s.id === id)).toBe(true)
    await wrapper.get('[data-testid="confirm-delete-session"]').trigger('click')
    await finish()
    expect(useDemoConversation('pc').state.sessions.some(s => s.id === id)).toBe(false)
    wrapper.unmount()
  })

  it('keeps mobile Enter as a newline and sends only with the button', async () => {
    useDemoConversation('mobile').newSession()
    const wrapper = mount(AiFindPrototype, { attachTo: document.body, props: { compact: true } })
    const input = wrapper.get('textarea[aria-label="描述数据需求"]')
    await input.setValue('找2025年煤炭运价')
    await input.trigger('keydown', { key: 'Enter' })
    expect(wrapper.findAll('.conversation-turn')).toHaveLength(0)
    await wrapper.get('[data-testid="chat-send"]').trigger('click'); await finish()
    expect(wrapper.findAll('.conversation-turn')).toHaveLength(1)
    wrapper.unmount()
  })
  it('lets users send, favorite, view details and edit without using the scene menu', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找2025年煤炭运价，按月查看')
    await wrapper.get('form.composer-box').trigger('submit')
    await finish()
    expect(wrapper.get('[data-testid="prototype-product-list"]').text()).toContain('煤炭公路运价明细数据集')
    await wrapper.get('.favorite').trigger('click')
    expect(wrapper.get('.favorite').text()).toContain('已收藏')
    await wrapper.get('.secondary-action').trigger('click')
    expect(wrapper.get('[role="dialog"]').attributes('aria-label')).toBe('商品详情')
    await wrapper.get('[aria-label="关闭弹窗"]').trigger('click')
    await wrapper.get('.condition-top button').trigger('click')
    await wrapper.get('.edit-panel input').setValue('2024 年')
    await wrapper.get('.edit-panel').trigger('submit')
    await finish()
    expect(wrapper.findAll('[data-testid="prototype-conditions"]').map(x => x.text()).join(' ')).toContain('2025')
    expect(wrapper.findAll('[data-testid="prototype-conditions"]').at(-1)!.text()).toContain('2024')
    wrapper.unmount()
  })
  it('submits a clarification with Enter and only then shows matching products', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找2025年苹果销量')
    await wrapper.get('form.composer-box').trigger('submit')
    await finish()
    expect(wrapper.find('.product-list').exists()).toBe(false)
    const answer = wrapper.get('textarea[aria-label="澄清回答"]')
    await answer.setValue('水果')
    await answer.trigger('keydown', { key: 'Enter' })
    await finish()
    expect(wrapper.get('.product-list').text()).toContain('水果苹果销量')
    wrapper.unmount()
  })
  it('only applies plan choices after the final confirmation', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找煤炭运价，必须按天查看、每天更新；再找山东货运量，必须按区县查看')
    await wrapper.get('form.composer-box').trigger('submit')
    await finish()
    const plans = wrapper.findAll('.plan-panel')
    await plans[0].get('.plan-option').trigger('click')
    await wrapper.get('.confirm-panel button').trigger('click')
    expect(wrapper.get('.confirm-panel').text()).toContain('山东货运量')
    expect(wrapper.find('.product-list').exists()).toBe(false)
    expect(wrapper.get('[data-testid="prototype-conditions"]').text()).toContain('按天查看')
    await plans[1].get('.keep-option').trigger('click')
    await wrapper.get('.confirm-panel button').trigger('click')
    await finish()
    expect(wrapper.findAll('[data-testid="prototype-conditions"]').at(-1)!.text()).toContain('按月查看')
    expect(wrapper.get('.product-list').text()).toContain('煤炭')
    wrapper.unmount()
  })
  it('shows processing steps as they run and keeps them after completion', async () => {
    const wrapper = mount(AiFindPrototype)
    await wrapper.get('textarea[aria-label="描述数据需求"]').setValue('找2025年煤炭运价，按月查看')
    await wrapper.get('form.composer-box').trigger('submit')
    const steps = wrapper.get('[data-testid="processing-steps"]')
    expect(steps.text()).toContain('解析需求')
    expect(steps.text()).toContain('拆分多需求')
    expect(steps.get('[data-step="parse"]').attributes('data-state')).toBe('active')
    expect(wrapper.find('.product-list').exists()).toBe(false)
    await vi.advanceTimersByTimeAsync(220)
    expect(steps.get('[data-step="parse"]').attributes('data-state')).toBe('done')
    expect(steps.get('[data-step="split"]').attributes('data-state')).toBe('active')
    await finish()
    expect(steps.findAll('[data-state="done"]')).toHaveLength(4)
    expect(wrapper.get('.product-list').exists()).toBe(true)
    wrapper.unmount()
  })

  it('opens usable data and a real preview panel instead of a generic success message', async () => {
    const wrapper = mount(AiFindPrototype)
    const run = useDemoConversation('pc').preset('access'); await finish(); await run
    await wrapper.findAll('button').find(b => b.text() === '立即使用')!.trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('数据预览')
    expect(wrapper.get('[role="dialog"]').find('table').exists()).toBe(true)
    expect(wrapper.get('[role="dialog"]').text()).not.toContain('已完成当前操作')
    wrapper.unmount()
  })
  it('keeps payment in an order awaiting activation and trial in application progress', async () => {
    const wrapper = mount(AiFindPrototype)
    const run = useDemoConversation('pc').preset('access'); await finish(); await run
    await wrapper.findAll('button').find(b => b.text() === '继续支付')!.trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('订单信息')
    await wrapper.get('[data-testid="confirm-demo-payment"]').trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('已支付，待开通')
    await wrapper.get('[aria-label="关闭弹窗"]').trigger('click')
    expect(wrapper.findAll('.product-actions button').filter(b => b.text() === '查看订单')).toHaveLength(1)
    await wrapper.findAll('button').find(b => b.text() === '提交试用申请')!.trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('申请信息')
    await wrapper.get('[data-testid="confirm-demo-trial"]').trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('申请已提交，待处理')
    wrapper.unmount()
  })

  it('reopens staged edits with their latest draft values', async () => {
    const wrapper = mount(AiFindPrototype)
    const demo = useDemoConversation('pc')
    const run = demo.send('找2025年煤炭运价，必须按天查看、每天更新'); await finish(); await run
    await wrapper.get('.condition-top button').trigger('click')
    await wrapper.get('.edit-panel input').setValue('2024 年')
    await wrapper.get('.edit-panel').trigger('submit'); await finish()
    await wrapper.get('.condition-top button').trigger('click')
    expect(wrapper.get<HTMLInputElement>('.edit-panel input').element.value).toBe('2024 年')
    expect(demo.tasks[0].year).toBe('2025 年')
    wrapper.unmount()
  })

})
