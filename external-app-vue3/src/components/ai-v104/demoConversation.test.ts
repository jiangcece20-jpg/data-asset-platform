import { describe, expect, it } from 'vitest'
import { createDemoConversation } from './demoConversation'

describe('AI找数前端演示流程', () => {
  it('accepts an input, asks one apple clarification and keeps the year', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年苹果销量')
    expect(demo.current.kind).toBe('clarify')
    expect(demo.current.products).toHaveLength(0)
    await demo.send('水果')
    expect(demo.current.kind).toBe('results')
    expect(demo.current.conditions.join(' ')).toContain('2025')
    expect(demo.current.products[0].name).toContain('苹果')
  })
  it('keeps each selection pending until all demands are selected and confirmed', async () => {
    const demo = createDemoConversation()
    await demo.send('找煤炭运价，必须按天查看、每天更新；再找山东货运量，必须按区县查看')
    const [a, b] = demo.current.plans
    expect(demo.current.products).toHaveLength(0)
    demo.choose(a.taskId, '0')
    expect(demo.tasks[0].grain).toBe('按天查看')
    await demo.confirm()
    expect(demo.current.missing).toContain(b.taskId)
    expect(demo.tasks[0].grain).toBe('按天查看')
    demo.choose(b.taskId, 'keep')
    await demo.confirm()
    expect(demo.tasks[0].grain).toBe('按月查看')
    expect(demo.tasks[0].frequency).toBe('每天更新')
    expect(demo.tasks[1].grain).toBe('按区县查看')
    expect(demo.current.tasks[1].status).toBe('无合适商品')
  })
  it('only accepts the explicitly accepted part of a combined plan', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年煤炭运价，必须按天查看、每天更新')
    await demo.send('按月查看可以，但仍要每天更新')
    expect(demo.tasks[0].grain).toBe('按天查看')
    expect(demo.current.proposed[demo.tasks[0].id].grain).toBe('按月查看')
    await demo.confirm()
    expect(demo.tasks[0].grain).toBe('按月查看')
    expect(demo.tasks[0].frequency).toBe('每天更新')
  })
  it('keeps effective conditions on a whole-batch failure and retries the same batch', async () => {
    const demo = createDemoConversation()
    demo.state.nextFailure = 'judgment'
    await demo.send('找2025年煤炭运价和山东货运路线，按月查看')
    expect(demo.current.kind).toBe('failure')
    expect(demo.current.products).toHaveLength(0)
    const conditions = [...demo.current.conditions]
    await demo.retry()
    expect(demo.current.kind).toBe('results')
    expect(demo.current.conditions).toEqual(conditions)
    expect(demo.current.taskIds).toHaveLength(2)
  })
  it('follows up only the newly requested demand and preserves the published result', async () => {
    const demo = createDemoConversation()
    await demo.send('找煤炭运价，再找2025年苹果销量')
    await demo.send('苹果先不找了')
    const published = JSON.stringify(demo.current)
    const publishedId = demo.current.id
    await demo.send('继续刚才苹果销量，是水果')
    expect(demo.current.taskIds).toHaveLength(1)
    expect(demo.current.conditions.join(' ')).toContain('2025')
    expect(JSON.stringify(demo.session.frames.find(f => f.id === publishedId))).toBe(published)
  })
  it('rolls back the last relaxation without undoing a later manual year edit', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年煤炭运价，必须按天查看、每天更新')
    demo.choose(demo.tasks[0].id, '0')
    await demo.confirm()
    await demo.edit(demo.tasks[0].id, { year: '2024 年' })
    await demo.rollback()
    expect(demo.tasks[0].year).toBe('2024 年')
    expect(demo.tasks[0].grain).toBe('按天查看')
    expect(demo.tasks[0].frequency).toBe('每天更新')
  })
  it('keeps collection fields after a simulated failure and validates contact', async () => {
    const demo = createDemoConversation()
    await demo.send('找煤炭运价')
    demo.openCollection()
    Object.assign(demo.state.collection, { price: '0-5000', name: '王女士', contact: 'not-an-email' })
    expect(demo.submitCollection()).toBe(false)
    demo.state.collection.contact = 'demo@example.com'
    demo.state.nextFailure = 'collection'
    expect(demo.submitCollection()).toBe(false)
    expect(demo.state.collection.price).toBe('0-5000')
    expect(demo.state.collection.contact).toBe('demo@example.com')
    expect(demo.submitCollection()).toBe(true)
  })
  it('does not substitute coal products for an unsupported target', async () => {
    const demo = createDemoConversation()
    await demo.send('找海底火山观测数据')
    expect(demo.current.products).toHaveLength(0)
    expect(demo.current.conditions.join(' ')).toContain('海底火山')
  })
  it('does not search for products until the user accepts the direct-question fallback', async () => {
    const demo = createDemoConversation()
    await demo.send('今天煤炭运价是多少？')
    expect(demo.current.kind).toBe('fallback')
    expect(demo.current.products).toHaveLength(0)
    await demo.continueFinding()
    expect(demo.current.kind).not.toBe('fallback')
    expect(demo.current.conditions.join(' ')).toContain('今天')
  })
  it('keeps past sessions and a shared favorite state inside the frontend demo', async () => {
    const demo = createDemoConversation()
    await demo.send('找煤炭运价')
    const firstId = demo.session.id
    const productId = demo.current.products[0].id
    demo.toggleFavorite(productId)
    demo.newSession()
    expect(demo.session.frames).toHaveLength(0)
    demo.activate(firstId)
    expect(demo.current.products[0].id).toBe(productId)
    expect(demo.state.favorites).toContain(productId)
    demo.toggleFavorite(productId)
    expect(demo.state.favorites).not.toContain(productId)
  })
  it('respects a requested API type and keeps incomparable budget visible', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年煤炭运价，只要API，单商品预算3000元/年')
    expect(demo.current.products.every(p => p.type === 'API')).toBe(true)
    expect(demo.current.conditions.join(' ')).toContain('API')
    expect(demo.current.products[0].budget).toContain('暂无法判断')
  })
  it('names the known gap of the selected collection demand', async () => {
    const demo = createDemoConversation()
    await demo.send('找山东货运量，必须按区县查看')
    demo.choose(demo.tasks[0].id, 'keep')
    await demo.confirm()
    demo.openCollection()
    expect(demo.state.collection.gaps.join(' ')).toContain('按地市查看')
    expect(demo.state.collection.gaps.join(' ')).toContain('按区县查看')
  })

  it('keeps the search step complete when the matching step fails', async () => {
    const demo = createDemoConversation()
    demo.state.nextFailure = 'judgment'
    await demo.send('找2025年煤炭运价')
    expect(demo.current.steps.find(s => s.id === 'search')?.state).toBe('done')
    expect(demo.current.steps.find(s => s.id === 'match')?.state).toBe('failed')
    expect(demo.current.products).toHaveLength(0)
    await demo.retry()
    expect(demo.current.steps.every(s => s.state === 'done')).toBe(true)
  })

  it('keeps the original batch while searching only an edited demand', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年煤炭运价和山东货运路线，按月查看')
    const [a, b] = demo.tasks
    expect(demo.current.conditions[0]).not.toContain('山东')
    expect(demo.current.conditions[1]).toContain('山东')
    const old = JSON.stringify(demo.current)
    const oldId = demo.current.id
    await demo.edit(a.id, { year: '2024 年' })
    expect(demo.current.taskIds).toEqual([a.id, b.id])
    expect(demo.current.searchedTaskIds).toEqual([a.id])
    expect(demo.current.tasks).toHaveLength(2)
    expect(demo.current.products.find(p => p.id === 'preview-route')?.evidence).toContainEqual({ label: '时间范围', fact: '覆盖 2025 年', state: 'met' })
    expect(JSON.stringify(demo.session.frames.find(f => f.id === oldId))).toBe(old)
    demo.state.nextFailure = 'judgment'
    await demo.edit(a.id, { year: '2023 年' })
    expect(demo.current.kind).toBe('failure')
    await demo.retry()
    expect(demo.current.searchedTaskIds).toEqual([a.id, b.id])
    expect(demo.current.taskIds).toEqual([a.id, b.id])
  })
  it('stages form edits alongside other pending choices until unified confirmation', async () => {
    const demo = createDemoConversation()
    await demo.send('找煤炭运价，必须按天查看、每天更新；再找山东货运量，必须按区县查看')
    const [a, b] = demo.tasks
    await demo.edit(a.id, { grain: '按月查看' })
    expect(demo.current.kind).toBe('relax')
    expect(a.grain).toBe('按天查看')
    expect(demo.current.proposed[a.id]).toEqual({ grain: '按月查看' })
    await demo.confirm()
    expect(demo.current.missing).toEqual([b.id])
    demo.choose(b.id, 'keep')
    await demo.confirm()
    expect(a.grain).toBe('按月查看')
    expect(demo.current.searchedTaskIds).toEqual([a.id])
    expect(demo.current.taskIds).toEqual([a.id, b.id])
    expect(demo.current.tasks[1].status).toBe('无合适商品')
  })

  it('previews and rolls back the selected demand without touching another demand', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年煤炭运价，必须按天查看、每天更新；再找山东货运量，必须按区县查看')
    const [a, b] = demo.tasks
    demo.choose(a.id, '0'); demo.choose(b.id, '0'); await demo.confirm()
    await demo.edit(a.id, { year: '2024 年' })
    expect(demo.rollbackPreview(a.id)).toContain('按天查看')
    expect(demo.rollbackPreview(a.id)).not.toContain('2025')
    await demo.rollback(a.id)
    expect(a.grain).toBe('按天查看')
    expect(a.year).toBe('2024 年')
    expect(b.grain).toBe('按地市查看')
    expect(demo.current.taskIds).toEqual([a.id, b.id])
    expect(demo.current.searchedTaskIds).toEqual([a.id])
    expect(demo.session.relaxations.map(r => r.taskId)).toEqual([b.id])
  })

  it('keeps undefined quality on the demand side and preserves explicit national coverage', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年全国新能源汽车销量，质量好一点')
    expect(demo.current.conditions.join(' ')).toContain('全国')
    expect(demo.current.conditions.join(' ')).toContain('质量标准尚未明确')
    expect(demo.current.products[0].evidence.some(e => e.fact.includes('质量'))).toBe(false)
    expect(demo.current.tasks[0].status).toBe('找到相关商品')
    expect(demo.current.products[0].best).toBeFalsy()
  })
  it('does not invent a viewing grain or narrow a vehicle target', async () => {
    const demo = createDemoConversation()
    await demo.send('找货运路线数据')
    expect(demo.current.conditions.join(' ')).not.toContain('按地市')
    expect(demo.current.conditions.join(' ')).not.toContain('山东')
    demo.newSession(); await demo.send('找汽车销量数据')
    expect(demo.current.conditions.join(' ')).toContain('汽车销量')
    expect(demo.current.conditions.join(' ')).not.toContain('新能源汽车')
  })

  it('answers purchase FAQ with search results and with no candidates without acquiring anything', async () => {
    const demo = createDemoConversation()
    await demo.send('找汽车销量数据，顺便告诉我平台的数据怎么买。')
    expect(demo.current.products.length).toBeGreaterThan(0)
    expect(demo.current.purchaseGuide).toContain('商品详情')
    expect(demo.state.acquired).toEqual({})
    demo.newSession(); await demo.send('找海底火山观测数据，顺便告诉我平台的数据怎么买')
    expect(demo.current.products).toHaveLength(0)
    expect(demo.current.purchaseGuide).toContain('商品详情')
    expect(demo.state.acquired).toEqual({})
  })
  it('does not invent purchase rules when the prototype has no reliable rules', async () => {
    const demo = createDemoConversation(undefined, { purchaseRulesAvailable: false })
    await demo.send('找汽车销量数据，平台的数据怎么买')
    expect(demo.current.purchaseGuide).toContain('暂时无法确认')
    expect(demo.state.acquired).toEqual({})
  })
  it('keeps a route unknown when only origin destination and price fields are known', async () => {
    const demo = createDemoConversation()
    await demo.preset('route-coverage')
    expect(demo.current.kind).toBe('results')
    expect(demo.current.tasks[0].status).toBe('部分匹配')
    expect(demo.current.products[0].evidence).toContainEqual({ label: '线路方向', fact: '是否包含榆林至天津港的煤炭公路运价，资料未说明', state: 'unknown' })
    expect(demo.current.products[0].best).toBeFalsy()
    expect(demo.current.plans).toHaveLength(0)
    await demo.retry()
    expect(demo.current.products[0].best).toBeFalsy()
    expect(demo.current.tasks[0].status).toBe('部分匹配')
  })

  it('keeps pending choices active when asking a purchase FAQ', async () => {
    const demo = createDemoConversation()
    await demo.send('找煤炭运价，必须按天查看、每天更新；再找山东货运量，必须按区县查看')
    const [a,b] = demo.tasks
    demo.choose(a.id, '0')
    await demo.send('平台的数据怎么买')
    expect(demo.current.kind).toBe('relax')
    expect(demo.current.choices[a.id]).toBe('0')
    expect(demo.current.purchaseGuide).toContain('商品详情')
    await demo.confirm(); expect(demo.current.missing).toEqual([b.id])
    expect(a.grain).toBe('按天查看')
    demo.choose(b.id, 'keep'); await demo.confirm()
    expect(a.grain).toBe('按月查看')
    expect(demo.current.taskIds).toEqual([a.id,b.id])
  })
  it('merges a later text choice with an earlier staged year', async () => {
    const demo = createDemoConversation()
    await demo.send('找2025年煤炭运价，必须按天查看、每天更新')
    const a = demo.tasks[0]
    await demo.edit(a.id, {year:'2024 年'})
    await demo.send('按月查看可以，但仍要每天更新')
    expect(demo.current.proposed[a.id]).toMatchObject({year:'2024 年',grain:'按月查看'})
    await demo.confirm()
    expect(a.year).toBe('2024 年'); expect(a.grain).toBe('按月查看')
  })
  it('keeps the original unknown-metadata preset as a partial candidate, including retries', async () => {
    const demo = createDemoConversation()
    await demo.preset('unknown')
    expect(demo.current.kind).toBe('results')
    expect(demo.current.tasks[0].status).toBe('部分匹配')
    expect(demo.current.products[0].evidence.some(e=> e.state === 'unknown')).toBe(true)
    await demo.retry()
    expect(demo.current.products.length).toBeGreaterThan(0)
  })

})
